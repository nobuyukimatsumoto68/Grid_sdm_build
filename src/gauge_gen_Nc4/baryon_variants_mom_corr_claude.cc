// 2 J_3 = (n_0 + n_2) - (n_1 + n_3) of a tuple string.
static int J3TwiceOf(const std::string &tuple)
{
  int up = 0;
  int down = 0;
  for(size_t i=0; i<tuple.size(); i++){
    int d = tuple[i] - '0';
    if( d % 2 == 0 ) up++;
    else down++;
  }
  return up - down;
}

static bool SameSector(const std::string &a, const std::string &b)
{
  if( PDTermTable::ParityOf(a) != PDTermTable::ParityOf(b) ) return false;
  int d = J3TwiceOf(a) - J3TwiceOf(b);
  if( d < 0 ) d = -d;
  if( (d % 8) != 0 ) return false;
  return true;
}

static std::string JoinStrings(const std::vector<std::string> &v, const std::string &sep)
{
  std::string out;
  for(size_t i=0; i<v.size(); i++){
    if( i > 0 ) out += sep;
    out += v[i];
  }
  return out;
}

