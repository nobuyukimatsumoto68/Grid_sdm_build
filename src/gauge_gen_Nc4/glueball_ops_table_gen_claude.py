#!/usr/bin/env python3
r"""
glueball_ops_table_gen_claude.py

Parse HiRep's generated glueball operator file (hirep_su4/LibHR/Observables/glueballs_op.c, the file HiRep compiles)
into a table, and write it as a C++ header for the Grid glueball code (glueball_h5_claude.cc).
Plan: glueball_grid_impl_plan_claude.md, Chunk 8.1.

Operators: Wilson loops projected onto O_h irreps (B. Berg and A. Billoire, Nucl. Phys. B221 (1983) 109;
R. C. Johnson, Phys. Lett. B114 (1982) 147), moving-frame little groups, generated by A. Rago's OpProjection.m.

Table contents:
  paths : for each of the npaths closed spatial loops, the list of signed steps +-d (d = 1,2,3 = x,y,z; HiRep
          direction d = Grid direction d-1). +d = forward link U_d(p), walker p -> p + d; -d = backward link
          U_d(p - d)^\dagger, walker p -> p - d. One step = s = 2^level lattice sites.
  moms  : the momenta (px,py,pz) in the order of eval_all_glueball_ops.
  ops   : for each operator (index = call order in eval_all_glueball_ops): momentum index, name, and terms
          (pm, path, m, coeff) meaning  coeff * exp(i \pi m s / L) * C^{pm}_{path}(p, t),
          C^+_i = \sum_x e^{2 \pi i p.x/L} Re tr_i(x),  C^-_i = i \sum_x e^{2 \pi i p.x/L} Im tr_i(x).

Usage:
  python3 glueball_ops_table_gen_claude.py <glueballs_op.c> <out.h>
  (import: parse_glueballs_op(path) -> dict with keys paths, moms, ops, cshift)
"""
import re
import sys


class Expr:
    """Linear form: dict key -> complex coefficient; key = (pm, path, m) for a C^{pm}_{path} term with shift-phase
    exponent m, or ('1', -1, m) for a pure (scalar x phase) factor."""

    def __init__(self, terms):
        self.terms = dict(terms)

    @staticmethod
    def lift(x):
        if isinstance(x, Expr):
            return x
        return Expr({("1", -1, 0): complex(x)})

    def __add__(self, other):
        o = Expr.lift(other)
        res = dict(self.terms)
        for k in o.terms:
            res[k] = res.get(k, 0.0) + o.terms[k]
        return Expr(res)

    def __radd__(self, other):
        return self.__add__(other)

    def __neg__(self):
        return Expr({k: -v for k, v in self.terms.items()})

    def __pos__(self):
        return self

    def __sub__(self, other):
        return self.__add__(-Expr.lift(other))

    def __rsub__(self, other):
        return Expr.lift(other).__add__(-self)

    def __mul__(self, other):
        o = Expr.lift(other)
        res = {}
        for ka, va in self.terms.items():
            for kb, vb in o.terms.items():
                if ka[0] != "1" and kb[0] != "1":
                    raise ValueError("product of two C terms: not linear")
                if ka[0] == "1":
                    key = (kb[0], kb[1], ka[2] + kb[2])
                else:
                    key = (ka[0], ka[1], ka[2] + kb[2])
                res[key] = res.get(key, 0.0) + va * vb
        return Expr(res)

    def __rmul__(self, other):
        return self.__mul__(other)


class CArray:
    def __init__(self, pm):
        self.pm = pm

    def __getitem__(self, i):
        return Expr({(self.pm, int(i), 0): 1.0 + 0.0j})


def parse_paths(src):
    """Simulate each pathN(int in) walk; return list of step lists (index = N)."""
    paths = {}
    pat_fn = re.compile(r"^static hr_complex path(\d+)\(int in\) \{\n(.*?)^\}", re.S | re.M)
    pat_read = re.compile(r"^w(\d) = pu_gauge_wrk\(site, (\d)\);$")
    pat_mv = re.compile(r"^site = (iup|idn)_wrk\(site, (\d)\);$")
    pat_mul = re.compile(r"^_suNg_times_suNg(_dagger)?\((\w+), \*?(\w+), \*w(\d)\);$")
    for mfn in pat_fn.finditer(src):
        ip = int(mfn.group(1))
        body = mfn.group(2)
        pos = [0, 0, 0]
        regs = {}
        links = []
        first = True
        for line in body.split("\n"):
            s = line.strip()
            if s == "" or s.startswith("suNg") or s.startswith("int ") or s.startswith("hr_complex"):
                continue
            if s in ("return p;", "_suNg_trace(p, res);"):
                continue
            m = pat_read.match(s)
            if m:
                regs[m.group(1)] = (tuple(pos), int(m.group(2)))
                continue
            m = pat_mv.match(s)
            if m:
                d = int(m.group(2))
                if m.group(1) == "iup":
                    pos[d - 1] += 1
                else:
                    pos[d - 1] -= 1
                continue
            m = pat_mul.match(s)
            if m:
                dag = m.group(1) is not None
                left = m.group(3)
                right = m.group(4)
                if first:
                    if left != "w2":
                        raise ValueError("path%d: first product does not start with w2: %s" % (ip, s))
                    links.append((regs["2"][0], regs["2"][1], False))
                    first = False
                links.append((regs[right][0], regs[right][1], dag))
                continue
            raise ValueError("path%d: unparsed statement: %s" % (ip, s))
        # links -> signed steps, with continuity + closure checks
        walker = [0, 0, 0]
        steps = []
        for off, d, dag in links:
            if not dag:
                if list(off) != walker:
                    raise ValueError("path%d: forward link not at walker" % ip)
                walker[d - 1] += 1
                steps.append(d)
            else:
                walker[d - 1] -= 1
                if list(off) != walker:
                    raise ValueError("path%d: backward link not at walker - d" % ip)
                steps.append(-d)
        if walker != [0, 0, 0]:
            raise ValueError("path%d: not closed" % ip)
        paths[ip] = steps
    n = len(paths)
    if sorted(paths) != list(range(n)):
        raise ValueError("path indices not contiguous")
    return [paths[i] for i in range(n)]


def parse_cshift(src):
    """c<k> = cexp(I * PI * ((m) * gb_shift_unit) / GLB_X) -> {k: m}"""
    pat = re.compile(r"^\s*c(\d) = cexp\(I \* PI \* \(\((-?[0-9.]+)\) \* gb_shift_unit\) / GLB_X\);$", re.M)
    res = {}
    for m in pat.finditer(src):
        mm = float(m.group(2))
        if mm != int(mm):
            raise ValueError("non-integer shift exponent")
        res[int(m.group(1))] = int(mm)
    return res


def parse_ops(src, cshift):
    pat_op = re.compile(r"^static void (OP_oneTr_\w+)\(hr_complex \*op_out\) \{\n\s*\*op_out =(.*?);\n\}", re.S | re.M)
    env = {"Cp": CArray("p"), "Cm": CArray("m"), "I": 1j}
    for k, m in cshift.items():
        env["c%d" % k] = Expr({("1", -1, m): 1.0 + 0.0j})
    defs = {}
    for mo in pat_op.finditer(src):
        name = mo.group(1)
        txt = mo.group(2)
        txt = txt.replace("mom_def_Cp_tr_paths", "Cp").replace("mom_def_Cm_tr_paths", "Cm")
        txt = " ".join(txt.split())
        e = Expr.lift(eval(txt, {"__builtins__": {}}, env))
        terms = []
        for (pm, ip, m), v in sorted(e.terms.items(), key=lambda kv: (kv[0][1], kv[0][0], kv[0][2])):
            if pm == "1":
                raise ValueError("%s: constant term" % name)
            if abs(v) == 0.0:
                continue
            terms.append((pm, ip, m, v))
        defs[name] = terms
    # call order
    n0 = src.index("void eval_all_glueball_ops(int t, hr_complex *numerical_op_out) {")
    body = src[n0:src.index("\n}\n", n0)]
    pat_mom = re.compile(r"eval_time_momentum_glueball_paths\(t, (-?\d+), (-?\d+), (-?\d+)\);")
    pat_call = re.compile(r"(OP_oneTr_\w+)\(numerical_op \+ (\d+)\);")
    moms = []
    ops = []
    for line in body.split("\n"):
        mm = pat_mom.search(line)
        if mm:
            moms.append(tuple(int(mm.group(i)) for i in (1, 2, 3)))
            continue
        mc = pat_call.search(line)
        if mc:
            name = mc.group(1)
            idx = int(mc.group(2))
            if idx != len(ops):
                raise ValueError("op index not sequential at %s" % name)
            pname = re.match(r"OP_oneTr_p_(m?\d+)_(m?\d+)_(m?\d+)_", name)
            pnum = tuple(int(x.replace("m", "-")) for x in pname.groups())
            if pnum != moms[-1]:
                raise ValueError("%s: momentum mismatch with eval call %s" % (name, moms[-1]))
            ops.append({"name": name, "mom": len(moms) - 1, "terms": defs[name]})
    return moms, ops


def parse_glueballs_op(fname):
    src = open(fname).read()
    paths = parse_paths(src)
    m = re.search(r"#define npaths (\d+)", src)
    if int(m.group(1)) != len(paths):
        raise ValueError("npaths mismatch")
    cshift = parse_cshift(src)
    if len(cshift) == 0:
        raise ValueError("no shift constants found")
    moms, ops = parse_ops(src, cshift)
    return {"paths": paths, "moms": moms, "ops": ops, "cshift": cshift}


def write_header(tab, fname, srcname):
    paths = tab["paths"]
    ops = tab["ops"]
    moms = tab["moms"]
    out = []
    out.append("// glueball_ops_table_claude.h -- GENERATED by glueball_ops_table_gen_claude.py, do not edit.")
    out.append("// Source: %s" % srcname)
    out.append("// Plan: glueball_grid_impl_plan_claude.md (Chunk 8.1).")
    out.append("// paths: signed steps +-d, d = 1,2,3 = x,y,z (Grid direction d-1); +d forward link U_d(p), p -> p+d;")
    out.append("//        -d backward link U_d(p-d)^\\dagger, p -> p-d; one step = 2^level sites.")
    out.append("// ops  : op = \\sum_terms coeff * exp(i \\pi m s / L) * C^{pm}_{path}(p_op, t), pm 0 = C^+ (Re tr), 1 = C^- (i Im tr).")
    out.append("#pragma once")
    out.append("")
    out.append("namespace GlueballTable {")
    out.append("")
    out.append("static const int npaths = %d;" % len(paths))
    out.append("static const int nmoms = %d;" % len(moms))
    out.append("static const int nops = %d;" % len(ops))
    nterm = sum(len(o["terms"]) for o in ops)
    out.append("static const int nterms = %d;" % nterm)
    out.append("")
    off = [0]
    flat = []
    for p in paths:
        flat.extend(p)
        off.append(len(flat))
    out.append("static const int path_offset[npaths + 1] = {")
    out.append(fmt_ints(off))
    out.append("};")
    out.append("static const int path_steps[%d] = {" % len(flat))
    out.append(fmt_ints(flat))
    out.append("};")
    out.append("")
    out.append("static const int mom[nmoms][3] = {")
    out.append(",\n".join("  {%d, %d, %d}" % p for p in moms))
    out.append("};")
    out.append("")
    out.append("static const int op_mom[nops] = {")
    out.append(fmt_ints([o["mom"] for o in ops]))
    out.append("};")
    toff = [0]
    tpm = []
    tpath = []
    tm = []
    tre = []
    tim = []
    for o in ops:
        for pm, ip, m, v in o["terms"]:
            tpm.append(0 if pm == "p" else 1)
            tpath.append(ip)
            tm.append(m)
            tre.append(v.real)
            tim.append(v.imag)
        toff.append(len(tpm))
    out.append("static const int op_term_offset[nops + 1] = {")
    out.append(fmt_ints(toff))
    out.append("};")
    out.append("static const int term_pm[nterms] = {")
    out.append(fmt_ints(tpm))
    out.append("};")
    out.append("static const int term_path[nterms] = {")
    out.append(fmt_ints(tpath))
    out.append("};")
    out.append("static const int term_m[nterms] = {")
    out.append(fmt_ints(tm))
    out.append("};")
    out.append("static const double term_re[nterms] = {")
    out.append(fmt_dbls(tre))
    out.append("};")
    out.append("static const double term_im[nterms] = {")
    out.append(fmt_dbls(tim))
    out.append("};")
    out.append("")
    out.append("static const char *op_name[nops] = {")
    out.append(",\n".join('  "%s"' % o["name"] for o in ops))
    out.append("};")
    out.append("")
    out.append("}  // namespace GlueballTable")
    out.append("")
    open(fname, "w").write("\n".join(out))


def fmt_ints(v):
    lines = []
    for i in range(0, len(v), 20):
        lines.append("  " + ", ".join("%d" % x for x in v[i:i + 20]))
    return ",\n".join(lines)


def fmt_dbls(v):
    lines = []
    for i in range(0, len(v), 6):
        lines.append("  " + ", ".join("%.17g" % x for x in v[i:i + 6]))
    return ",\n".join(lines)


if __name__ == "__main__":
    src = sys.argv[1]
    dst = sys.argv[2]
    tab = parse_glueballs_op(src)
    lens = {}
    for p in tab["paths"]:
        lens[len(p)] = lens.get(len(p), 0) + 1
    print("paths", len(tab["paths"]), "lengths", sorted(lens.items()))
    print("moms", len(tab["moms"]), tab["moms"])
    print("ops", len(tab["ops"]), "terms", sum(len(o["terms"]) for o in tab["ops"]))
    print("shift exponents", tab["cshift"])
    ms = sorted(set(t[2] for o in tab["ops"] for t in o["terms"]))
    print("total shift exponents in terms", ms)
    write_header(tab, dst, src)
    print("wrote", dst)
